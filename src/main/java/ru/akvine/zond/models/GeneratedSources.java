package ru.akvine.zond.models;

import com.github.javaparser.ast.CompilationUnit;
import com.github.javaparser.ast.body.ClassOrInterfaceDeclaration;
import com.github.javaparser.ast.body.MethodDeclaration;
import com.github.javaparser.ast.body.TypeDeclaration;
import com.github.javaparser.ast.comments.Comment;
import com.github.javaparser.ast.expr.StringLiteralExpr;

import java.nio.file.Path;
import java.util.List;
import java.util.Optional;
import java.util.Set;
import java.util.regex.Pattern;
import java.util.stream.Collectors;

/**
 * Сгенерированный код: кодеки протокола Hazelcast, классы protobuf и ANTLR. Править его вручную бессмысленно -
 * изменения пропадут при следующей генерации, - поэтому находки в нем не показываются. Сам файл читается:
 * по нему видно, что класс или метод используется.
 * <p>
 * О генерации говорит аннотация {@code @Generated} на классе либо комментарий до тела класса:
 * "Auto-generated by ...", "@generated", "Generated by the protocol buffer compiler. DO NOT EDIT!"
 */
public final class GeneratedSources {
    private static final String GENERATED = "Generated";
    private static final Pattern GENERATED_COMMENT = Pattern.compile(
            "(?i)\\b(auto-?generated|automatically generated|@generated|generated (by|from)|do not (edit|modify))\\b");

    private static final String MYBATIS_CRITERIA = "GeneratedCriteria";
    private static final Set<String> MYBATIS_MAPPER_METHODS = Set.of(
            "countByExample", "deleteByExample", "deleteByPrimaryKey", "insert", "insertSelective",
            "selectByExample", "selectByExampleWithBLOBs", "selectByPrimaryKey", "updateByExampleSelective",
            "updateByExample", "updateByExampleWithBLOBs", "updateByPrimaryKeySelective", "updateByPrimaryKey",
            "updateByPrimaryKeyWithBLOBs", "selectOneByExample", "insertBatch");
    // Меньше - это скорее свой интерфейс, где совпало одно-два имени
    private static final int MYBATIS_MAPPER_MIN_METHODS = 4;
    private static final String TO_STRING = "toString";
    private static final String MYBATIS_TO_STRING_HASH = "Hash = ";

    private GeneratedSources() {
    }

    /**
     * @return пути сгенерированных файлов среди исходников
     */
    public static Set<Path> of(List<SourceFile> sources) {
        return sources.stream()
                .filter(source -> isGenerated(source.unit()))
                .map(SourceFile::path)
                .collect(Collectors.toSet());
    }

    public static boolean isGenerated(CompilationUnit unit) {
        Optional<TypeDeclaration<?>> type = unit.getTypes().getFirst();
        if (type.isPresent() && type.get().getAnnotations().stream()
                .anyMatch(annotation -> GENERATED.equals(annotation.getName().getIdentifier()))) {
            return true;
        }
        if (type.isPresent() && isMyBatisGenerated(type.get())) {
            return true;
        }
        // Шапка файла и описание класса; комментарии внутри методов о генерации кода не говорят
        int bodyStart = type.flatMap(declaration -> declaration.getName().getBegin())
                .map(position -> position.line)
                .orElse(Integer.MAX_VALUE);
        return unit.getAllComments().stream()
                .filter(comment -> comment.getBegin().map(position -> position.line < bodyStart).orElse(false))
                .map(Comment::getContent)
                .anyMatch(content -> GENERATED_COMMENT.matcher(content).find());
    }

    // MyBatis Generator часто настраивают без комментариев (suppressAllComments), но его классы узнаются по
    // устройству: XxxExample с вложенным GeneratedCriteria, XxxMapper только из методов генератора, модель с
    // toString вида "Hash = " + hashCode()
    private static boolean isMyBatisGenerated(TypeDeclaration<?> type) {
        boolean example = type.getMembers().stream()
                .anyMatch(member -> member instanceof TypeDeclaration<?> nested
                        && MYBATIS_CRITERIA.equals(nested.getNameAsString()));
        if (example) {
            return true;
        }
        List<String> methods = type.getMethods().stream().map(MethodDeclaration::getNameAsString).toList();
        boolean mapper = type instanceof ClassOrInterfaceDeclaration declaration && declaration.isInterface()
                && methods.size() >= MYBATIS_MAPPER_MIN_METHODS && MYBATIS_MAPPER_METHODS.containsAll(methods);
        boolean model = type.getMethodsByName(TO_STRING).stream()
                .anyMatch(method -> method.findAll(StringLiteralExpr.class).stream()
                        .anyMatch(literal -> MYBATIS_TO_STRING_HASH.equals(literal.getValue())));
        return mapper || model;
    }
}
